#!/usr/bin/env node
// Generate a static MDX import manifest for Academy courses
// This enables Next to include MDX modules in the bundle while still selecting by slug at runtime.

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import matter from 'gray-matter'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const repoRoot = path.resolve(__dirname, '..')
const coursesDir = path.resolve(repoRoot, 'packages/ui/src/data/academy/courses')
const outFile = path.resolve(repoRoot, 'apps/academy/lib/mdx-manifest.generated.ts')

/** @type {(s: string) => string} */
function toSlug(file) {
  return file.replace(/\.mdx?$/, '')
}

function main() {
  if (!fs.existsSync(coursesDir)) {
    console.error(`[manifest] courses directory not found: ${coursesDir}`)
    process.exit(1)
  }

  const files = fs.readdirSync(coursesDir).filter((f) => f.endsWith('.mdx'))
  files.sort()

  const imports = []
  const mapEntries = []
  const frontmatterEntries = []

  for (const file of files) {
    const slug = toSlug(file)
    // Use TS path alias so Next can resolve modules across the monorepo.
    // IMPORTANT: Do NOT include '/src' in the spec. The alias '@workspace/ui/*'
    // already maps to '../../packages/ui/src/*' in app tsconfig paths. If we emit
    // '@workspace/ui/src/...', it resolves to '../../packages/ui/src/src/...'.
    // The correct spec is '@workspace/ui/data/academy/courses/<file>'.
    const aliasedImport = '@workspace/ui/data/academy/courses/' + file
    const varName = `mod_${slug.replace(/[^a-zA-Z0-9_]/g, '_')}`
    imports.push(`const ${varName} = () => import('${aliasedImport}');`)
    mapEntries.push(`  '${slug}': ${varName},`)

    // Extract frontmatter now to avoid runtime parsing
    const abs = path.join(coursesDir, file)
    const raw = fs.readFileSync(abs, 'utf8')
    const { data } = matter(raw)
    // Normalize frontmatter values to match shared types
    const fm = { ...data, slug }
    // Coerce commonly stringified numeric fields to numbers when possible
    if (fm && typeof fm === 'object') {
      const maybeNum = (v) => (typeof v === 'string' && v.trim() !== '' && !Number.isNaN(Number(v)) ? Number(v) : v)
      if ('version' in fm) fm.version = maybeNum(fm.version)
      if ('readingTime' in fm) fm.readingTime = maybeNum(fm.readingTime)
      if ('estimatedReadingTime' in fm) fm.estimatedReadingTime = maybeNum(fm.estimatedReadingTime)
      if ('durationHours' in fm) fm.durationHours = maybeNum(fm.durationHours)
    }
    // Stable JSON with double quotes
    frontmatterEntries.push(`  '${slug}': ${JSON.stringify(fm)},`)
  }

  const content = `// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by scripts/generate-academy-mdx-manifest.mjs
/* eslint-disable */

import type { ReactElement } from 'react';
import type { AcademyCourseFrontmatter } from '@workspace/ui/data/academy/types';

${imports.join('\n')}

export type MDXModule = { default: (props: any) => ReactElement };

export const MDX_COURSE_MODULES = {
${mapEntries.join('\n')}
} as const satisfies Record<string, () => Promise<MDXModule>>;

export const MDX_COURSE_FRONTMATTER = {
${frontmatterEntries.join('\n')}
} as const satisfies Record<string, AcademyCourseFrontmatter>;
`

  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, content)
  console.log(`[manifest] wrote ${outFile} with ${files.length} entries`)
}

main()
